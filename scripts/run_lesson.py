"""Replay the lesson end to end against the compose database.

1. Naive listing (offset paging, one customer query per order): run the load, rank statements.
2. Fix the N+1 (customers in one query): same load, rank again.
3. Keyset paging on the ordering index: same load, rank again.
4. Covering index (expand, then contract): same load, rank again.

Each phase resets pg_stat_statements first and uses the same page sequence, so the rankings compare.
Plans are written next to their query in sql/explain/, the rankings to sql/explain/results.md.
"""
import os
import subprocess
import sys
import time

import requests

from app import stats
from scripts import lab, load

PORT = os.environ.get("APP_PORT", "8142")
BASE_URL = f"http://localhost:{PORT}"
REQUESTS = int(os.environ.get("LOAD_REQUESTS", "300"))

PHASES = [  # (label, strategy, index state after migration number)
    ("1 naive: offset paging, N+1 customer lookups", "naive", 0),
    ("2 N+1 fixed: customers fetched in one query", "batched", 0),
    ("3 keyset paging on (created_at DESC, id DESC)", "keyset", 0),
    ("4 keyset + covering index (expand, then contract)", "keyset", 2),
]


def start_app():
    process = subprocess.Popen([sys.executable, "-m", "uvicorn", "app.main:app", "--port", PORT, "--log-level", "warning"])
    for _ in range(60):
        try:
            if requests.get(f"{BASE_URL}/health", timeout=1).ok:
                return process
        except requests.ConnectionError:
            time.sleep(0.5)
    process.terminate()
    raise RuntimeError("the listing app did not start")


def capture(connection, name):
    path = lab.EXPLAIN_DIR / f"{name}.sql"
    lab.plan_lines(connection, path)                       # warm-up run, discarded
    lines = lab.plan_lines(connection, path)
    (lab.EXPLAIN_DIR / f"{name}.txt").write_text("\n".join(lines) + "\n")
    print(f"  plan {name:30} {lab.execution_ms(lines):10.3f} ms {lab.buffers_touched(lines):8} pages")
    return {"ms": lab.execution_ms(lines), "pages": lab.buffers_touched(lines)}


def short(query, width=96):
    return " ".join(query.split())[:width]


def main():
    plans, phases = {}, []
    server = start_app()
    try:
        with lab.connect() as connection:
            for label, strategy, index_state in PHASES:
                print(f"== {label}")
                if label.startswith(("1", "4")):                  # states change only here
                    lab.reset_to(connection, index_state)
                if label.startswith("1"):
                    for name in ("e1_offset_page1", "e1_offset_page100", "e1_offset_page10000"):
                        plans[name] = capture(connection, name)
                bookmarks = load.bookmarks_for(strategy)
                load.run_load(BASE_URL, strategy, 5, bookmarks=bookmarks)    # warm the caches, not measured
                stats.reset()
                started = time.perf_counter()
                timings = load.run_load(BASE_URL, strategy, REQUESTS, bookmarks=bookmarks)
                wall_s = time.perf_counter() - started
                phases.append({"label": label, "by_time": stats.top("total_exec_time"), "by_calls": stats.top("calls"),
                               "total_ms": stats.total_database_time_ms(), "calls": stats.total_calls(), "wall_s": wall_s,
                               "medians": load.median_by_page(timings)})
                print(f"  {REQUESTS} requests in {wall_s:.1f} s, database time {phases[-1]['total_ms']:.0f} ms")
                print(f"  top by total time: {short(phases[-1]['by_time'][0]['query'])}")
                print(f"  top by calls:      {short(phases[-1]['by_calls'][0]['query'])}")
                if label.startswith("3"):
                    for name in ("e2_keyset_page1", "e2_keyset_page10000"):
                        plans[name] = capture(connection, name)
                if label.startswith("4"):
                    plans["e3_keyset_page10000_covering"] = capture(connection, "e3_keyset_page10000_covering")
    finally:
        server.terminate()
        server.wait()
    write_results(phases, plans)


def ranking_table(entries):
    rows = ["| Statement | Calls | Total ms | Mean ms |", "|---|---:|---:|---:|"]
    rows += [f"| `{short(entry['query'], 150).replace('|', '/')}` | {entry['calls']} | {entry['total_exec_time']:.1f} | "
             f"{entry['mean_exec_time']:.3f} |" for entry in entries]
    return rows


def write_results(phases, plans):
    out = ["# Results of the last `make run`", "",
           f"Generated by `scripts/run_lesson.py`: {REQUESTS} requests per phase, page sequence fixed by seed 1 "
           "(pages 0, 1, 2, 50, 100, 5000 and 10000, chosen at random). The plans are the `.txt` files here.", "",
           "## Same load, four phases", "",
           "| Phase | Database time ms | Statements | Wall clock s | Median ms: page 1 | page 100 | page 5,000 | page 10,000 |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for phase in phases:
        median = phase["medians"]
        out.append(f"| {phase['label']} | {phase['total_ms']:.0f} | {phase['calls']} | {phase['wall_s']:.1f} | {median[0]:.1f} | "
                   f"{median[100]:.1f} | {median[5000]:.1f} | {median[10000]:.1f} |")
    out += ["", "## Plans for the deep page", "", "| Plan | Execution ms | Pages touched |", "|---|---:|---:|"]
    out += [f"| `{name}` | {plan['ms']:.3f} | {plan['pages']} |" for name, plan in plans.items()]
    for position in (0, len(phases) - 1):
        phase = phases[position]
        out += ["", f"## Top ten, phase {phase['label']}", "", "### By total time", ""] + ranking_table(phase["by_time"])
        out += ["", "### By calls", ""] + ranking_table(phase["by_calls"])
    for phase in phases[1:-1]:
        out += ["", f"## Top two, phase {phase['label']}", ""]
        out += ranking_table(phase["by_time"][:2]) + [""] + ranking_table(phase["by_calls"][:2])
    (lab.EXPLAIN_DIR / "results.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
